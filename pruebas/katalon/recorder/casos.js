// Definición de los 7 casos de prueba E2E para Katalon Recorder (extensión de Chrome).
// Cada comando es [comando, objetivo, valor], igual que en la tabla de Katalon Recorder.
// `node generar-suite.js` convierte este archivo en la suite HTML que se importa en la extensión.
'use strict';

const WEB = 'http://localhost:5173';
const CLAVE = 'Prueba2026';

const X = {
  h1: (t) => `xpath=//h1[normalize-space(.)='${t}']`,
  campo: (etiqueta) => `xpath=//input[@id=//label[starts-with(normalize-space(.),'${etiqueta}')]/@for]`,
  campoModal: (etiqueta) => `xpath=//div[@role='dialog']//input[@id=//label[starts-with(normalize-space(.),'${etiqueta}')]/@for]`,
  botonForm: (t) => `xpath=//form//button[@type='submit' and normalize-space(.)='${t}']`,
  botonModal: (t) => `xpath=//div[@role='dialog']//button[@type='submit' and normalize-space(.)='${t}']`,
  botonConfirmacion: (t) => `xpath=//div[@role='alertdialog']//button[normalize-space(.)='${t}']`,
  avisoExito: (t) => `xpath=//div[@aria-live='polite']/div[@role='status'][.//p[normalize-space(.)='Listo']][.//p[contains(normalize-space(.),'${t}')]]`,
  alertaForm: 'xpath=//form//div[@role=\'alert\']',
  requisito: (r, estado) => `xpath=//div[@id='requisitos-password']//li[contains(normalize-space(.),'${r}') and contains(normalize-space(.),'${estado}')]`,
  tarjetaEquipo: (n) => `xpath=//a[@data-testid='tarjeta-equipo'][.//h3[normalize-space(.)='${n}']]`,
  tarjetaProyecto: (n) => `xpath=//a[@data-testid='tarjeta-proyecto'][.//span[normalize-space(.)='${n}']]`,
  columna: (c) => `xpath=//section[starts-with(@aria-labelledby,'columna-')]//h2[normalize-space(.)='${c}']`,
  tareaEnColumna: (c, t) => `xpath=//section[starts-with(@aria-labelledby,'columna-')][.//h2[normalize-space(.)='${c}']]//button[@data-testid='abrir-tarea'][.//span[normalize-space(.)='${t}']]`,
  tarea: (t) => `xpath=//button[@data-testid='abrir-tarea'][.//span[normalize-space(.)='${t}']]`,
  nav: (t) => `xpath=//nav[@aria-label='Navegación principal']//*[self::a or self::button][normalize-space(.)='${t}']`,
};

// Pasos comunes: sesión limpia, datos únicos, registro e inicio de sesión de un usuario nuevo.
const iniciarConUsuarioNuevo = (prefijo) => [
  ['open', `${WEB}/login`, ''],
  ['runScript', 'localStorage.clear(); return "ok"', ''],
  ['runScript', 'return String(Date.now())', 'ts'],
  ['store', `${prefijo}.\${ts}@taskflow.test`, 'email'],
  ['open', `${WEB}/register`, ''],
  ['waitForElementPresent', X.h1('Crear cuenta'), ''],
  ['type', X.campo('Nombre completo'), `Usuario ${prefijo}`],
  ['type', X.campo('Correo electrónico'), '${email}'],
  ['type', X.campo('Contraseña'), CLAVE],
  ['type', X.campo('Confirmar contraseña'), CLAVE],
  ['click', X.botonForm('Crear cuenta'), ''],
  ['waitForElementPresent', "xpath=//div[@role='status'][contains(normalize-space(.),'Cuenta creada correctamente')]", ''],
  ['type', 'css=form input[type="email"]', '${email}'],
  ['type', 'css=form input[autocomplete="current-password"]', CLAVE],
  ['click', X.botonForm('Iniciar sesión'), ''],
  ['waitForElementPresent', X.h1('Mis equipos'), ''],
];

const crearEquipo = (nombre) => [
  ['click', "xpath=//main//header//button[normalize-space(.)='Nuevo equipo']", ''],
  ['waitForElementPresent', X.campoModal('Nombre del equipo'), ''],
  ['type', X.campoModal('Nombre del equipo'), nombre],
  ['click', X.botonModal('Crear equipo'), ''],
  ['waitForElementPresent', X.tarjetaEquipo(nombre), ''],
];

const crearProyectoYAbrirTablero = (equipo, proyecto) => [
  ['click', X.tarjetaEquipo(equipo), ''],
  ['waitForElementPresent', `xpath=//main//header//h1[normalize-space(.)='${equipo}']`, ''],
  ['click', "xpath=//section[@aria-labelledby='titulo-proyectos']//button[normalize-space(.)='Nuevo proyecto']", ''],
  ['waitForElementPresent', X.campoModal('Nombre del proyecto'), ''],
  ['type', X.campoModal('Nombre del proyecto'), proyecto],
  ['click', X.botonModal('Crear proyecto'), ''],
  ['waitForElementPresent', X.tarjetaProyecto(proyecto), ''],
  ['click', X.tarjetaProyecto(proyecto), ''],
  ['waitForElementPresent', `xpath=//main//header//h1[normalize-space(.)='${proyecto}']`, ''],
];

const crearTarea = (titulo) => [
  ['click', "xpath=//main//header//button[@aria-keyshortcuts='n' and normalize-space(.)='Nueva tarea']", ''],
  ['waitForElementPresent', X.campoModal('Título de la tarea'), ''],
  ['type', X.campoModal('Título de la tarea'), titulo],
  ['click', X.botonModal('Crear tarea'), ''],
  ['waitForElementPresent', X.tareaEnColumna('Por Hacer', titulo), ''],
];

